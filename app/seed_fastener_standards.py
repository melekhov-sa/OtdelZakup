def seed_fastener_standards() -> tuple[int, int]:
    """Insert/update fastener standards. Returns (inserted, updated)."""
    session = get_db_session()
    try:
        existing = {
            (r.standard_kind, r.standard_code): r
            for r in session.query(StandardRef).all()
        }

        inserted = updated = 0
        seen: set = set()
        for kind, code, title, item_type, item_subtype in _FASTENER_STANDARDS:
            key = (kind, code)
            if key in seen:
                continue
            seen.add(key)
            if key not in existing:
                ref = StandardRef(
                    standard_kind=kind,
                    standard_code=code,
                    standard_key=f"{kind}-{code}",
                    title=title,
                    item_type=item_type,
                    item_subtype=item_subtype,
                    is_active=True,
                )
                session.add(ref)
                inserted += 1
            else:
                ref = existing[key]
                changed = False
                if not ref.item_type and item_type:
                    ref.item_type = item_type
                    changed = True
                if not ref.item_subtype and item_subtype:
                    ref.item_subtype = item_subtype
                    changed = True
                if not ref.title and title:
                    ref.title = title
                    changed = True
                if changed:
                    updated += 1

        session.commit()
        return inserted, updated
    finally:
        session.close()
