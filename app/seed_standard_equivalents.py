def seed_standard_equivalents():
    """Fill the standard_equivalents table when it is still empty."""
    from app.matching.standard_analogs import invalidate_standard_analogs_cache

    session = get_db_session()
    try:
        if session.query(StandardEquivalent).count() > 0:
            return
        for src_canonical, dst_canonical in DIN_GOST_PAIRS:
            session.add(StandardEquivalent(
                src_canonical=src_canonical,
                dst_canonical=dst_canonical,
                confidence=100,
                is_active=True,
            ))
        session.commit()
    finally:
        session.close()

    invalidate_standard_analogs_cache()
